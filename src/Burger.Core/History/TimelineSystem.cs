using System.Text.RegularExpressions;
using Burger.Core.Data;
using Burger.Core.Model;
using Burger.Core.Script;

namespace Burger.Core.History;

/// <summary>A date the player can pick on the start screen.</summary>
public sealed record Bookmark(GameDate Date, string Name, string Desc);

/// <summary>A span of history with its own tab on the start screen and the dates it suggests.</summary>
public sealed class Era
{
    public string Name = "", Desc = "";
    public GameDate From, To;
    public List<GameDate> Suggested = new();
    public bool Contains(GameDate d) => d >= From && d <= To;
}

/// <summary>Who owned every state on a date (history/timeline/snapshots.txt, generated by tools/import-history.py): a tag per state in the order of the sorted state keys.</summary>
public sealed class Snapshot
{
    public GameDate Date;
    public string Name = "";
    public string[] Owners = Array.Empty<string>();
    public Dictionary<string, string> Names = new();
    /// <summary>States that fuse into one on this date: indexes into the sorted state keys, the first is the state that stays (snapshots.txt: <c>groups = { 5+7+9 12+15 }</c>).</summary>
    public List<int[]> Groups = new();
    /// <summary>The snapshot of the first start date: it adds the tribes to the data of the project and keeps its relations and countries.</summary>
    public bool Keep;
}

/// <summary>A dated change of the world: states change hands, countries are annexed or renamed.</summary>
public sealed class TimelineEvent
{
    public GameDate Date;
    public string Name = "";
    public Node Node = null!;
}

/// <summary>
/// The history that leads from the first start date to a later one. A game can start on any date between <c>start_date</c> and <c>latest_start_date</c> (common/defines.txt):
/// <see cref="Apply"/> sets the date and replays every event up to it in order, so the map, the names and the forces are those of that day. Events live in
/// <c>history/timeline/*.txt</c>:
/// <code>
/// bookmark = { date = -490.9.12 name = "Marathon" desc = "..." }
/// event = {
///     date = -334.1.1  name = "Alexander crosses into Asia"
///     transfer = { from = ACH to = MAC regions = { anatolia } count = 6 }   # regions (the state key without its number) and count are optional
///     settle   = { to = TAG regions = { a } count = N }                     # states nobody owns
///     give     = { to = TAG regions = { a } count = N }                     # the states of these regions, whoever owns them
///     annex    = { from = ION to = MAC }                                    # every state, army and fleet of 'from'
///     rename   = { tag = MAC name = "Macedonian Empire" }
/// }
/// </code>
/// Events are applied before the game starts, directly (no events, no aggressive expansion): they are the world the game begins with.
/// </summary>
public sealed class TimelineSystem
{
    private readonly Game _game;
    public readonly List<Bookmark> Bookmarks = new();
    public readonly List<TimelineEvent> Events = new();
    public readonly List<Era> Eras = new();
    public readonly List<Snapshot> Snapshots = new();
    private string _stateHash = "";
    /// <summary>The sorted keys of every state of the map as the files define them (a snapshot lists its owners in this order, also after states were fused).</summary>
    private List<string> _baseKeys = new();
    private int _stateCount;
    /// <summary>A named shape on the globe: polygons and boxes in degrees of longitude and latitude.</summary>
    public sealed class Area
    {
        public string Name = "";
        public readonly List<double[]> Polygons = new();
        public readonly List<double[]> Boxes = new();
        public bool Contains(double lon, double lat)
        {
            foreach (var b in Boxes) if (lon >= b[0] && lon <= b[2] && lat >= b[1] && lat <= b[3]) return true;
            foreach (var p in Polygons)
            {
                bool inside = false;
                int n = p.Length / 2;
                for (int i = 0, j = n - 1; i < n; j = i++)
                {
                    double xi = p[2 * i], yi = p[2 * i + 1], xj = p[2 * j], yj = p[2 * j + 1];
                    if ((yi > lat) != (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
                }
                if (inside) return true;
            }
            return false;
        }
    }

    public readonly Dictionary<string, Area> Areas = new(StringComparer.OrdinalIgnoreCase);
    private readonly Dictionary<State, (double Lon, double Lat)> _centre = new();
    private static readonly Regex RegionSuffix = new(@"(_m\d+)?_\d+$", RegexOptions.Compiled);

    public TimelineSystem(Game game) { _game = game; }

    public GameDate Earliest => _game.Data.Defines.StartDate;
    /// <summary>The last date a game may start on (the start date itself when the project has no timeline).</summary>
    public GameDate Latest => _game.Data.Defines.LatestStartDate > Earliest ? _game.Data.Defines.LatestStartDate : Earliest;
    public bool Enabled => Latest > Earliest && (Events.Count > 0 || Snapshots.Count > 0);

    public void Load()
    {
        Bookmarks.Clear();
        Events.Clear();
        Eras.Clear();
        Snapshots.Clear();
        foreach (var root in DataLoader.ParseFileOrFolder(_game.Data, "history/timeline"))
            foreach (var n in root.All)
            {
                if (n.Children == null) continue;
                if (n.Key != "bookmark" && n.Key != "event" && (n.Has("polygon") || n.Has("box"))) { ReadArea(n); continue; }
                if (n.Key == "era") { ReadEra(n); continue; }
                if (n.Key == "states") { _stateHash = n.GetString("hash") ?? ""; _stateCount = n.GetInt("count"); continue; }
                if (n.Key == "snapshot") { ReadSnapshot(n); continue; }
                if (!GameDate.TryParse(n.GetString("date") ?? "", out var date)) { Log.Error($"history/timeline: '{n.Key}' has no valid date", n.Location); continue; }
                switch (n.Key.ToLowerInvariant())
                {
                    case "bookmark": Bookmarks.Add(new Bookmark(date, n.GetString("name") ?? date.ToDisplay(), n.GetString("desc") ?? "")); break;
                    case "event": Events.Add(new TimelineEvent { Date = date, Name = n.GetString("name") ?? "", Node = n }); break;
                    default: Log.Error($"history/timeline: unknown entry '{n.Key}' (bookmark or event)", n.Location); break;
                }
            }
        var sorted = Events.OrderBy(e => e.Date.TotalDays).ToList(); // stable: file order inside one day is kept
        Events.Clear();
        Events.AddRange(sorted);
        var marks = Bookmarks.OrderBy(b => b.Date.TotalDays).ToList();
        Bookmarks.Clear();
        Bookmarks.AddRange(marks);
    }

    private void ReadSnapshot(Node n)
    {
        if (!GameDate.TryParse(n.GetString("date") ?? "", out var date)) { Log.Error("history/timeline: a snapshot needs a date", n.Location); return; }
        var snap = new Snapshot { Date = date, Name = n.GetString("name") ?? date.ToDisplay(), Owners = n.GetList("owners").ToArray(), Keep = n.GetBool("keep") };
        foreach (var g in n.GetList("groups"))
        {
            var ids = g.Split('+', StringSplitOptions.RemoveEmptyEntries).Select(x => int.TryParse(x, out var v) ? v : -1).ToArray();
            if (ids.Length >= 2 && ids.All(v => v >= 0)) snap.Groups.Add(ids);
        }
        if (n.Get("names") is { Children: not null } names) foreach (var c in names.Children) if (c.Value != null) snap.Names[c.Key] = c.Value;
        Snapshots.Add(snap);
    }

    /// <summary>The snapshot closest in time to a date, when there is one near enough to matter (the first start date keeps the map of the 500 BCE data).</summary>
    public Snapshot? SnapshotFor(GameDate date)
    {
        if (Snapshots.Count == 0) return null;
        var best = Snapshots.OrderBy(s => Math.Abs(s.Date.TotalDays - date.TotalDays)).First();
        // before the first snapshot the data of the first start date is the better map
        if (date < Snapshots[0].Date && Math.Abs(best.Date.TotalDays - date.TotalDays) > 50 * 365) return null;
        return best;
    }

    private void ReadEra(Node n)
    {
        if (!GameDate.TryParse(n.GetString("from") ?? "", out var from) || !GameDate.TryParse(n.GetString("to") ?? "", out var to)) { Log.Error("history/timeline: an era needs from and to dates", n.Location); return; }
        var era = new Era { Name = n.GetString("name") ?? from.YearDisplay, Desc = n.GetString("desc") ?? "", From = from, To = to };
        foreach (var t in n.GetList("suggested"))
            if (GameDate.TryParse(t, out var d)) era.Suggested.Add(d); else Log.Error($"history/timeline: era '{era.Name}': bad suggested date '{t}'", n.Location);
        Eras.Add(era);
    }

    public Era? EraAt(GameDate d) => Eras.FirstOrDefault(e => e.Contains(d)) ?? Eras.LastOrDefault(e => e.From <= d);

    private void ReadArea(Node n)
    {
        var a = new Area { Name = n.Key };
        foreach (var p in n.GetAll("polygon"))
        {
            var v = p.Items().Select(t => double.Parse(t, System.Globalization.CultureInfo.InvariantCulture)).ToArray();
            if (v.Length >= 6 && v.Length % 2 == 0) a.Polygons.Add(v); else Log.Error($"history/timeline: area '{n.Key}' has a polygon with {v.Length} numbers", p.Location);
        }
        foreach (var b in n.GetAll("box"))
        {
            var v = b.Items().Select(t => double.Parse(t, System.Globalization.CultureInfo.InvariantCulture)).ToArray();
            if (v.Length == 4) a.Boxes.Add(v); else Log.Error($"history/timeline: area '{n.Key}' has a box with {v.Length} numbers (west south east north)", b.Location);
        }
        Areas[n.Key] = a;
    }

    /// <summary>The middle of a state, in degrees: the average of its land locations.</summary>
    private (double Lon, double Lat) CentreOf(State s)
    {
        if (_centre.TryGetValue(s, out var c)) return c;
        var map = _game.World.Map;
        var land = s.Locations.Where(l => l.IsLand).ToList();
        if (land.Count == 0) land = s.Locations.ToList();
        double x = land.Average(l => l.CenterX), y = land.Average(l => l.CenterY);
        return _centre[s] = (-180.0 + 360.0 * x / map.Width, map.Settings.NorthLat - (map.Settings.NorthLat - map.Settings.SouthLat) * y / map.Height);
    }

    private bool InAreas(State s, List<string> names)
    {
        if (names.Count == 0) return true;
        var (lon, lat) = CentreOf(s);
        foreach (var name in names)
        {
            if (!Areas.TryGetValue(name, out var a)) { Log.ErrorOnce("timeline-area:" + name, $"history/timeline: unknown area '{name}'"); continue; }
            if (a.Contains(lon, lat)) return true;
        }
        return false;
    }

    /// <summary>Gives every state to the country the snapshot names, clears the relations of the first start date and names the countries as they were called.</summary>
    private bool ApplySnapshot(Snapshot snap, bool clearRelations = true)
    {
        var w = _game.World;
        var ordered = w.States.OrderBy(s => s.Key, StringComparer.Ordinal).ToList();
        string hash = Convert.ToHexString(System.Security.Cryptography.SHA1.HashData(System.Text.Encoding.UTF8.GetBytes(string.Join("\n", ordered.Select(s => s.Key))))).ToLowerInvariant();
        if (hash != _stateHash || snap.Owners.Length != ordered.Count)
        {
            Log.Error($"history/timeline/snapshots.txt was made for other states ({_stateCount} states, {snap.Owners.Length} in the snapshot, {ordered.Count} in the map): run tools/import-history.py again");
            return false;
        }
        var byTag = new Dictionary<string, Country?>(StringComparer.Ordinal) { ["_"] = null };
        for (int i = 0; i < ordered.Count; i++)
        {
            string tag = snap.Owners[i];
            if (!byTag.TryGetValue(tag, out var c)) { c = w.GetCountry(tag); if (c == null) Log.ErrorOnce("snapshot-tag:" + tag, $"history/timeline/snapshots.txt: unknown country '{tag}'"); byTag[tag] = c; }
            var s = ordered[i];
            s.Owner = c;
            s.Cores.Clear();
            s.Claims.Clear();
            if (c != null) s.Cores.Add(c);
            foreach (var l in s.Locations) _game.Warfare.SetController(l, c, silent: true);
        }
        w.RefreshOwnership();
        var R = w.Relations;
        if (!snap.Keep && clearRelations) { R.Alliances.Clear(); R.MilitaryAccess.Clear(); R.Guarantees.Clear(); R.Subjects.Clear(); R.Truces.Clear(); R.Pacts.Clear(); R.Opinions.Clear(); }
        foreach (var c in w.Countries)
        {
            if (snap.Names.TryGetValue(c.Tag, out var name)) { c.DefaultName = name; c.Name = name; c.NameVariants.Clear(); }
        }
        FixCapitals();
        return true;
    }

    /// <summary>
    /// The states of this date: what the snapshot lists as one group becomes one state (the first of the group stays; the others are gone, their locations, tax, manpower, buildings,
    /// cores, claims and people join it, and their keys still find it). Only groups whose states have one owner now are fused. The map file keeps the fine states for every other date.
    /// </summary>
    public int FuseStates(Snapshot snap)
    {
        if (_baseKeys.Count == 0) _baseKeys = _game.World.States.Select(s => s.Key).OrderBy(k => k, StringComparer.Ordinal).ToList();
        if (snap.Groups.Count == 0) return 0;
        int fused = 0;
        foreach (var g in snap.Groups)
        {
            if (g.Any(i => i >= _baseKeys.Count)) continue;
            fused += FuseGroup(g.Select(i => _baseKeys[i]).ToArray(), force: false);
        }
        if (fused == 0) return 0;
        FinishFusing();
        Log.Info($"{snap.Name}: {fused} states fused into their neighbours, {_game.World.States.Count} states left");
        return fused;
    }

    /// <summary>Fuses the states for the date the world is at, when that has not been done (a game is about to start on it).</summary>
    public void FuseForStart()
    {
        if (FusedGroups.Count > 0 || !Enabled) return;
        var snap = SnapshotFor(_game.World.Date);
        if (snap != null && snap.Groups.Count > 0 && FuseStates(snap) > 0) _game.RaiseMapChanged();
    }

    /// <summary>The groups fused in this world, as state keys (the first stays): a save lists them so that loading it fuses the same states first.</summary>
    public readonly List<string[]> FusedGroups = new();

    /// <summary>Fuses the groups of a save (state keys) into a world that has not been fused yet; groups already fused are skipped.</summary>
    public void FuseKeys(IEnumerable<string[]> groups)
    {
        int fused = 0;
        foreach (var g in groups) fused += FuseGroup(g, force: true);
        if (fused > 0) FinishFusing();
    }

    private void FinishFusing()
    {
        var w = _game.World;
        if (_gone.Count > 0) { _game.Titles.OnStatesFused(_gone); w.States.RemoveAll(_gone.Contains); _gone.Clear(); }   // one pass: removing 30,000 states one by one from a list of 37,000 is slow
        for (int i = 0; i < w.States.Count; i++) w.States[i].Index = i;
        _centre.Clear();
        w.RefreshOwnership();
    }

    private readonly HashSet<State> _gone = new();

    private int FuseGroup(string[] keys, bool force)
    {
        var w = _game.World;
        var states = keys.Select(k => w.GetState(k)).ToList();
        if (states.Any(s => s == null)) return 0;
        var keep = states[0]!;
        var others = states.Skip(1).Where(s => s != keep && !_gone.Contains(s!)).Distinct().ToList();
        if (others.Count == 0) return 0;
        if (!force && others.Any(s => s!.Owner != keep.Owner)) return 0;
        int fused = 0;
        foreach (var o in others)
        {
            foreach (var l in o!.Locations) { l.State = keep; keep.Locations.Add(l); }
            o.Locations.Clear();
            keep.Manpower += o.Manpower; keep.Tax += o.Tax;
            foreach (var (b, n) in o.Buildings) keep.Buildings[b] = keep.Buildings.GetValueOrDefault(b) + n;
            foreach (var (b, n) in o.Damaged) keep.Damaged[b] = keep.Damaged.GetValueOrDefault(b) + n;
            keep.Cores.UnionWith(o.Cores); keep.Claims.UnionWith(o.Claims);
            keep.Demilitarized |= o.Demilitarized;
            _game.Population.FuseStates(keep, o);
            _gone.Add(o);
            w.StateByKey[o.Key] = keep;
            fused++;
        }
        FusedGroups.Add(new[] { keep.Key }.Concat(others.Select(o => o!.Key)).ToArray());
        return fused;
    }

    /// <summary>A country whose capital is not its own gets the land nearest the middle of its states.</summary>
    private void FixCapitals()
    {
        foreach (var c in _game.World.Countries)
        {
            if (!c.Exists) continue;
            if (c.Capital == null || c.Capital.Owner != c)
            {
                var cx = c.OwnedStates.Average(s => (double)CentreOf(s).Lon); var cy = c.OwnedStates.Average(s => (double)CentreOf(s).Lat);
                var near = c.OwnedStates.Where(s => s.Locations.Any(l => l.IsLand)).OrderBy(s => { var (lo, la) = CentreOf(s); return (lo - cx) * (lo - cx) + (la - cy) * (la - cy); }).FirstOrDefault();
                c.Capital = near?.Locations.FirstOrDefault(l => l.IsLand);
            }
        }
    }

    // ------------------------------------------------------------------------------------- previewing a date on a loaded world (the start screen)
    private Dictionary<Country, (string Name, string Default, Location? Capital)>? _baseCountries;
    private Dictionary<State, (Country? Owner, List<Country> Cores)>? _baseStates;

    /// <summary>Remembers the world as the project data made it, so the start screen can show any date without loading the world again. Call right after Load().</summary>
    public void CaptureBase()
    {
        var w = _game.World;
        _baseCountries = w.Countries.ToDictionary(c => c, c => (c.RawName, c.DefaultName, c.Capital));
        _baseStates = w.States.ToDictionary(s => s, s => (s.Owner, s.Cores.ToList()));
    }

    /// <summary>The name a country has in the project data, before any snapshot renamed it.</summary>
    public string BaseNameOf(Country c) => _baseCountries != null && _baseCountries.TryGetValue(c, out var b) ? Localisation.Get(b.Name) : c.Name;

    /// <summary>The capital a country has in the project data (null if it has none).</summary>
    public Location? BaseCapitalOf(Country c) => _baseCountries != null && _baseCountries.TryGetValue(c, out var b) ? b.Capital : c.Capital;

    /// <summary>The world as the project data made it: owners, cores, names and capitals (what a snapshot and the events change).</summary>
    private void RestoreBase()
    {
        if (_baseCountries == null || _baseStates == null) return;
        foreach (var (c, b) in _baseCountries) { c.Name = b.Name; c.DefaultName = b.Default; c.Capital = b.Capital; }
        foreach (var (s, b) in _baseStates)
        {
            s.Owner = b.Owner; s.Cores.Clear(); foreach (var core in b.Cores) s.Cores.Add(core); s.Claims.Clear();
            foreach (var l in s.Locations) _game.Warfare.SetController(l, b.Owner, silent: true);
        }
        _game.World.RefreshOwnership();
    }

    /// <summary>Makes the world that of a date, as loading it for that date would (the start screen has only shown it): the project data, then the history up to the date.</summary>
    public void StartAt(GameDate date)
    {
        RestoreBase();
        Apply(date, fuseStates: true);
        _game.RaiseMapChanged();
    }

    /// <summary>Shows the map of a date on the loaded world at once: who owns what and what the countries are called. Only the map is changed (a game is started by loading the date).</summary>
    public void Preview(GameDate date)
    {
        var w = _game.World;
        if (_baseCountries == null || _baseStates == null) return;
        if (date < Earliest) date = Earliest;
        if (date > Latest) date = Latest;
        w.Date = date;
        RestoreBase();
        var snap = SnapshotFor(date);
        if (snap == null || !ApplySnapshot(snap, clearRelations: false)) FixCapitals();
        _game.RefreshNames();
        _game.RaiseMapChanged();
    }

    /// <summary>The event names up to a date, newest last (what has happened by then).</summary>
    public IEnumerable<TimelineEvent> Until(GameDate date) => Events.Where(e => e.Date <= date);

    /// <summary>The bookmark at or just before a date.</summary>
    public Bookmark? BookmarkAt(GameDate date) => Bookmarks.LastOrDefault(b => b.Date <= date);

    /// <summary>Sets the date and replays the history up to it. Call once, right after loading the world and before the game starts.</summary>
    public void Apply(GameDate date, bool fuseStates = false)
    {
        var w = _game.World;
        if (date < Earliest) date = Earliest;
        if (date > Latest) date = Latest;
        w.Date = date;
        int applied = 0;
        var snap = SnapshotFor(date);
        if (snap != null && ApplySnapshot(snap)) applied++;
        foreach (var e in Events.Where(e => e.Date <= date && (snap == null || e.Date > snap.Date)).OrderBy(e => e.Date.TotalDays))
        {
            foreach (var op in e.Node.All)
            {
                if (op.Children == null) continue;
                try { Run(op); }
                catch (Exception ex) { Log.Error($"history/timeline '{e.Name}': {op.Key}: {ex.Message}", op.Location); }
            }
            applied++;
        }
        if (fuseStates && snap != null) FuseStates(snap);
        w.RefreshOwnership();
        // forces of a country that lost its last state (by transfers) stay where they stand, under whoever owns the land, or are gone
        foreach (var d in w.Divisions.Where(d => !d.Owner.Exists).ToList())
        {
            if (d.Location.Owner is { Exists: true } o) d.Owner = o; else _game.Warfare.DestroyDivision(d);
        }
        foreach (var a in w.Armies.Where(a => !a.Owner.Exists).ToList())
        {
            var o = a.Divisions.Select(d => d.Owner).FirstOrDefault(x => x.Exists);
            if (o != null) a.Owner = o; else w.Armies.Remove(a);
        }
        foreach (var f in _game.Navy.Fleets.Where(f => !f.Owner.Exists).ToList()) _game.Navy.DisbandFleet(f);
        foreach (var c in w.Countries.Where(c => !c.Exists)) w.Relations.RemoveCountry(c);
        _game.RefreshNames();
        Log.Info($"Start date {date.ToDisplay()}: {applied} historical events applied");
    }

    private static bool InRegions(State s, List<string> regions) => regions.Count == 0 || regions.Contains(RegionSuffix.Replace(s.Key, ""), StringComparer.OrdinalIgnoreCase);

    private Country? Tag(Node op, string key)
    {
        var c = _game.World.GetCountry(op.GetString(key));
        if (c == null) Log.Error($"history/timeline: unknown country '{op.GetString(key)}' for '{key}'", op.Location);
        return c;
    }

    private void Run(Node op)
    {
        switch (op.Key.ToLowerInvariant())
        {
            case "transfer":
                {
                    var from = Tag(op, "from"); var to = Tag(op, "to");
                    if (from == null || to == null) return;
                    var regions = op.GetList("regions"); var areas = op.GetList("areas");
                    int count = op.GetInt("count", int.MaxValue);
                    foreach (var s in from.OwnedStates.Where(s => InRegions(s, regions) && InAreas(s, areas))
                                 .OrderBy(s => s.Key, StringComparer.Ordinal).Take(count).ToList()) Move(s, to);
                    break;
                }
            case "settle":
                {
                    // land nobody owns at the first start date: a people takes it
                    var to = Tag(op, "to");
                    if (to == null) return;
                    var regions = op.GetList("regions"); var areas = op.GetList("areas");
                    int count = op.GetInt("count", int.MaxValue);
                    foreach (var s in _game.World.States.Where(s => s.Owner == null && InRegions(s, regions) && InAreas(s, areas))
                                 .OrderBy(s => s.Key, StringComparer.Ordinal).Take(count).ToList()) Move(s, to);
                    break;
                }
            case "give":
                {
                    // whoever owns the regions now: for the later centuries, where the earlier holders no longer matter
                    var to = Tag(op, "to");
                    if (to == null) return;
                    var regions = op.GetList("regions"); var areas = op.GetList("areas");
                    int count = op.GetInt("count", int.MaxValue);
                    var only = op.Has("from") ? Tag(op, "from") : null;
                    foreach (var s in _game.World.States.Where(s => s.Owner != to && (only == null || s.Owner == only) && InRegions(s, regions) && InAreas(s, areas))
                                 .OrderBy(s => s.Key, StringComparer.Ordinal).Take(count).ToList()) Move(s, to);
                    break;
                }
            case "annex":
                {
                    var from = Tag(op, "from"); var to = Tag(op, "to");
                    if (from == null || to == null || from == to) return;
                    foreach (var s in from.OwnedStates.ToList()) Move(s, to);
                    // the forces go with the land
                    foreach (var d in _game.World.Divisions.Where(d => d.Owner == from)) d.Owner = to;
                    foreach (var a in _game.World.Armies.Where(a => a.Owner == from)) a.Owner = to;
                    foreach (var f in _game.Navy.Fleets.Where(f => f.Owner == from)) f.Owner = to;
                    break;
                }
            case "rename":
                {
                    var c = Tag(op, "tag");
                    if (c == null) return;
                    string name = op.GetString("name") ?? c.Name;
                    c.DefaultName = name;
                    c.Name = name;
                    c.NameVariants.Clear();
                    break;
                }
            default:
                Log.Error($"history/timeline: unknown operation '{op.Key}' (transfer, settle, give, annex, rename)", op.Location);
                break;
        }
    }

    /// <summary>A state changes hands without any of the effects of a conquest.</summary>
    private void Move(State s, Country to)
    {
        var old = s.Owner;
        if (old == to) return;
        s.Owner = to;
        s.Cores.Add(to);
        s.Claims.Remove(to);
        foreach (var l in s.Locations) _game.Warfare.SetController(l, to, silent: true);
        _game.World.RefreshOwnership();
        if (old != null && old.Capital != null && old.Capital.State == s)
            old.Capital = old.OwnedStates.SelectMany(x => x.Locations).FirstOrDefault(l => l.IsLand);
        to.Capital ??= s.Locations.FirstOrDefault(l => l.IsLand);
    }
