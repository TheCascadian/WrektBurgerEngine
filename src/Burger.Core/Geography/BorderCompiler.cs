using System.Text;

namespace Burger.Core.Geography;

/// <summary>What one area looked like from <see cref="Day"/> until its next entry. <c>none</c> means nobody held it.</summary>
public sealed record BorderEntry(int Day, string Owner, string Control, string Source, string Note, string Where);

/// <summary>The result of replaying every claim: per-area history plus anything contradictory found on the way.</summary>
public sealed class BorderTimeline
{
    public const string None = "none";
    public readonly Dictionary<string, List<BorderEntry>> ByArea = new(StringComparer.Ordinal);
    public readonly List<GeoIssue> Issues = new();

    public BorderEntry? At(string area, int day)
    {
        if (!ByArea.TryGetValue(area, out var list)) return null;
        BorderEntry? best = null;
        foreach (var e in list) { if (e.Day > day) break; best = e; }
        return best;
    }
}

public static class BorderCompiler
{
    /// <summary>
    /// Replays claims by date; inside one date every remove runs before any add, each group in file order, so the result never depends
    /// on which polity file sorts first. A later add always wins, but taking an area another polity still holds is reported.
    /// </summary>
    public static BorderTimeline Replay(BorderSet set)
    {
        var tl = new BorderTimeline();
        var holder = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var group in set.Claims.Select((c, i) => (c, i)).GroupBy(x => x.c.Day).OrderBy(g => g.Key))
        {
            var touched = new HashSet<string>(StringComparer.Ordinal);
            foreach (var (c, _) in group.OrderBy(x => x.i))
                foreach (var a in c.Remove)
                {
                    if (!holder.TryGetValue(a, out var h) || h != c.Tag)
                        tl.Issues.Add(new(GeoSeverity.Warning, $"{c.Tag} removes '{a}' on {HistoricalCalendar.Format(c.Day)} but does not hold it", c.Where));
                    else { holder.Remove(a); Put(tl, a, new BorderEntry(c.Day, BorderTimeline.None, BorderTimeline.None, c.Source, c.Note, c.Where)); touched.Add(a); }
                }
            foreach (var (c, _) in group.OrderBy(x => x.i))
                foreach (var a in c.Add)
                {
                    if (holder.TryGetValue(a, out var h) && h != c.Tag)
                        tl.Issues.Add(new(GeoSeverity.Error, $"overlap: '{a}' is claimed by {c.Tag} on {HistoricalCalendar.Format(c.Day)} while {h} still holds it", c.Where));
                    holder[a] = c.Tag;
                    Put(tl, a, new BorderEntry(c.Day, c.Tag, c.Control, c.Source, c.Note, c.Where));
                }
        }
        return tl;
    }

    // one entry per area per day: the last write that day wins
    private static void Put(BorderTimeline tl, string area, BorderEntry e)
    {
        if (!tl.ByArea.TryGetValue(area, out var list)) tl.ByArea[area] = list = new List<BorderEntry>();
        if (list.Count > 0 && list[^1].Day == e.Day) list[^1] = e; else list.Add(e);
    }

    /// <summary>The text of <c>history/geography/_generated_borders.txt</c>. Same input, same bytes.</summary>
    /// <param name="pieces">Cuts the atoms of an area into pieces joined by real borders. An area that is in several pieces becomes several provinces: the largest keeps the area's name, the others are called name_p2, name_p3 ...; each follows the area's claims.</param>
    public static string Geography(BorderSet set, BorderTimeline tl, Func<string[], List<string[]>>? pieces = null)
    {
        var sb = new StringBuilder();
        sb.Append("# GENERATED by `burger borders build`. DO NOT EDIT.\n");
        sb.Append("# Edit map/areas.txt and history/borders/*.txt, then rebuild. Claims with source = generated are terrain-driven placeholders, not attested history.\n");
        sb.Append("settings = { dynamic = no }\n");
        sb.Append("property = { key = control kind = categorical }\n");
        sb.Append("property = { key = claim_source kind = categorical }\n");
        var provinces = new List<(string Area, string Id, string[] Atoms)>();
        foreach (var name in set.AreaOrder)
        {
            var parts = pieces?.Invoke(set.Areas[name]) ?? new List<string[]> { set.Areas[name] };
            for (int i = 0; i < parts.Count; i++) provinces.Add((name, i == 0 ? name : $"{name}_p{i + 1}", parts[i]));
        }
        foreach (var (_, id, atoms) in provinces)
            sb.Append("province = { id = ").Append(id).Append(" atoms = { ").Append(string.Join(' ', atoms)).Append(" } }\n");
        foreach (var (area, id, _) in provinces)
        {
            if (!tl.ByArea.TryGetValue(area, out var list)) continue;
            Track(sb, id, "owner", list, e => e.Owner);
            Track(sb, id, "control", list, e => e.Control);
            Track(sb, id, "claim_source", list, e => e.Source);
        }
        return sb.ToString();
    }

    private static void Track(StringBuilder sb, string area, string prop, List<BorderEntry> list, Func<BorderEntry, string> value)
    {
        sb.Append("track = { subject = ").Append(area).Append(" property = ").Append(prop);
        foreach (var e in list) sb.Append(' ').Append(HistoricalCalendar.ToScript(e.Day)).Append(" = ").Append(value(e));
        sb.Append(" }\n");
    }

    /// <summary>A state file for the start date <paramref name="day"/>: one state per area, owned by whoever held it that day.</summary>
    public static string States(BorderSet set, BorderTimeline tl, int day)
    {
        var sb = new StringBuilder();
        sb.Append("# GENERATED by `burger borders build --year`. DO NOT EDIT. Snapshot of ").Append(HistoricalCalendar.Format(day)).Append(".\n");
        foreach (var name in set.AreaOrder)
        {
            var e = tl.At(name, day);
            sb.Append(name).Append(" = { name = \"").Append(name).Append('"');
            if (e != null && e.Owner != BorderTimeline.None) sb.Append(" owner = ").Append(e.Owner);
            sb.Append(" locations = { ").Append(string.Join(' ', set.Areas[name])).Append(" } }\n");
        }
        return sb.ToString();
    }
}
